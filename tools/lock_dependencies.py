"""Resolve reviewed pins on the native platform and record selected wheel hashes.

Network access to public PyPI is required only for deliberate lock regeneration.
This never installs the project or opens any research data or model artifact.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
PATCHES = {"linux": (3, 11, 17), "windows": (3, 11, 9)}


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def reviewed_versions() -> dict[str, str]:
    versions = {}
    for line in (ROOT / "requirements/versions.txt").read_text().splitlines():
        if line and not line.startswith("#"):
            name, version = line.split("==")
            versions[canonical(name)] = version
    return versions


def generate(target: str) -> None:
    native = "windows" if sys.platform == "win32" else sys.platform
    if target != native or sys.version_info[:3] != PATCHES[target]:
        raise ValueError(f"Generate {target} locks natively on CPython {PATCHES[target]}")
    if platform.machine().lower() not in {"x86_64", "amd64"} or sys.maxsize <= 2**32:
        raise ValueError("Only Linux x86_64 and Windows AMD64 locks are supported")
    constraints = reviewed_versions()
    records = {}
    cache = ROOT / ".pytest_cache"
    cache.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="lock-generation-", dir=cache) as temporary:
        for group in ("runtime", "dev"):
            report = Path(temporary) / f"{group}.json"
            subprocess.run(
                [
                    sys.executable,
                    "-m",
                    "pip",
                    "--isolated",
                    "--disable-pip-version-check",
                    *(["--use-feature=truststore"] if target == "windows" else []),
                    "install",
                    "--dry-run",
                    "--ignore-installed",
                    "--only-binary=:all:",
                    "--index-url",
                    "https://pypi.org/simple",
                    "--report",
                    str(report),
                    "-r",
                    str(ROOT / f"requirements/{group}.in"),
                    "-c",
                    str(ROOT / "requirements/versions.txt"),
                ],
                check=True,
            )
            packages = {}
            for item in json.loads(report.read_text(encoding="utf-8"))["install"]:
                name = canonical(item["metadata"]["name"])
                version = item["metadata"]["version"]
                info = item["download_info"]
                url = urlsplit(info["url"])
                digest = info["archive_info"]["hashes"]["sha256"]
                if constraints.get(name) != version:
                    raise ValueError(f"Unreviewed dependency/version: {name}=={version}")
                if url.scheme != "https" or url.hostname != "files.pythonhosted.org":
                    raise ValueError("Resolver selected a non-PyPI artifact")
                if not url.path.endswith(".whl") or not re.fullmatch(r"[0-9a-f]{64}", digest):
                    raise ValueError("Every dependency must have a selected wheel and SHA-256")
                packages[name] = (version, digest)
            records[group] = packages
    if any(records["dev"].get(name) != value for name, value in records["runtime"].items()):
        raise ValueError("Runtime and development resolutions disagree")
    sources = "\n".join(
        "\n".join((ROOT / f"requirements/{name}").read_text().splitlines())
        for name in ("runtime.in", "dev.in", "versions.txt")
    )
    for group, packages in records.items():
        header = (
            "# Generated by tools/lock_dependencies.py; review changes before use.\n"
            f"# Platform: {target} x86_64; CPython {'.'.join(map(str, PATCHES[target]))}\n"
            f"# Input SHA256: {hashlib.sha256(sources.encode()).hexdigest()}\n"
            "--index-url https://pypi.org/simple\n--only-binary=:all:\n"
        )
        entries = "".join(
            f"{name}=={version} --hash=sha256:{digest}\n"
            for name, (version, digest) in sorted(packages.items())
        )
        output = ROOT / f"requirements/{group}-{target}-py311.lock"
        output.write_text(header + entries, encoding="utf-8", newline="\n")
        print(f"Locked {len(packages)} packages: {output.name}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--platform", choices=sorted(PATCHES), required=True)
    generate(parser.parse_args().platform)
